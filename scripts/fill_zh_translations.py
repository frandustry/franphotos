def main():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    strings = catalog["strings"]
    missing = []
    for key in strings:
        if key not in ZH:
            missing.append(key)
            continue
        entry = strings[key]
        locs = entry.setdefault("localizations", {})
        locs["zh-Hans"] = {
            "stringUnit": {"state": "translated", "value": ZH[key]}
        }
    if missing:
        print("keys without a zh mapping (add to ZH):")
        for k in missing:
            print("  -", k)
        return 1
    CATALOG.write_text(json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True),
                       encoding="utf-8")
    print(f"translated {len(ZH)} keys")
    return 0


if __name__ == "__main__":
    sys.exit(main())
